/* ============================================================
   A hand-drawn 5x7 bitmap font.

   Canvas `fillText` at 6-8px is mush: the rasteriser antialiases,
   hinting shifts baselines, and the result changes with every OS.
   An arcade screen should be exact. Every glyph below is a grid of
   pixels drawn as integer rects, so text is crisp at any whole
   scale, identical on every machine, and needs no webfont to load.
   ============================================================ */
(function (global) {
  "use strict";

  var G = {};

  function def(chars, art) { G[chars] = art.split("/"); }

  def("A", ".###./#...#/#...#/#####/#...#/#...#/#...#");
  def("B", "####./#...#/#...#/####./#...#/#...#/####.");
  def("C", ".###./#...#/#..../#..../#..../#...#/.###.");
  def("D", "####./#...#/#...#/#...#/#...#/#...#/####.");
  def("E", "#####/#..../#..../####./#..../#..../#####");
  def("F", "#####/#..../#..../####./#..../#..../#....");
  def("G", ".###./#...#/#..../#.###/#...#/#...#/.####");
  def("H", "#...#/#...#/#...#/#####/#...#/#...#/#...#");
  def("I", "#####/..#../..#../..#../..#../..#../#####");
  def("J", "..###/...#./...#./...#./...#./#..#./.##..");
  def("K", "#...#/#..#./#.#../##.../#.#../#..#./#...#");
  def("L", "#..../#..../#..../#..../#..../#..../#####");
  def("M", "#...#/##.##/#.#.#/#.#.#/#...#/#...#/#...#");
  def("N", "#...#/##..#/##..#/#.#.#/#..##/#..##/#...#");
  def("O", ".###./#...#/#...#/#...#/#...#/#...#/.###.");
  def("P", "####./#...#/#...#/####./#..../#..../#....");
  def("Q", ".###./#...#/#...#/#...#/#.#.#/#..#./.##.#");
  def("R", "####./#...#/#...#/####./#.#../#..#./#...#");
  def("S", ".####/#..../#..../.###./....#/....#/####.");
  def("T", "#####/..#../..#../..#../..#../..#../..#..");
  def("U", "#...#/#...#/#...#/#...#/#...#/#...#/.###.");
  def("V", "#...#/#...#/#...#/#...#/#...#/.#.#./..#..");
  def("W", "#...#/#...#/#...#/#.#.#/#.#.#/##.##/#...#");
  def("X", "#...#/#...#/.#.#./..#../.#.#./#...#/#...#");
  def("Y", "#...#/#...#/.#.#./..#../..#../..#../..#..");
  def("Z", "#####/....#/...#./..#../.#.../#..../#####");

  def("0", ".###./#...#/#..##/#.#.#/##..#/#...#/.###.");
  def("1", "..#../.##../..#../..#../..#../..#../.###.");
  def("2", ".###./#...#/....#/...#./..#../.#.../#####");
  def("3", "####./....#/....#/.###./....#/....#/####.");
  def("4", "...#./..##./.#.#./#..#./#####/...#./...#.");
  def("5", "#####/#..../#..../####./....#/#...#/.###.");
  def("6", ".###./#...#/#..../####./#...#/#...#/.###.");
  def("7", "#####/....#/...#./..#../.#.../.#.../.#...");
  def("8", ".###./#...#/#...#/.###./#...#/#...#/.###.");
  def("9", ".###./#...#/#...#/.####/....#/#...#/.###.");

  def(" ", "...../...../...../...../...../...../.....");
  def(".", "...../...../...../...../...../.##../.##..");
  def(",", "...../...../...../...../.##../..#../.#...");
  def("!", "..#../..#../..#../..#../..#../...../..#..");
  def("?", ".###./#...#/....#/..##./..#../...../..#..");
  def("'", "..#../..#../...../...../...../...../.....");
  def('"', ".#.#./.#.#./...../...../...../...../.....");
  def(":", "...../..#../..#../...../..#../..#../.....");
  def(";", "...../..#../..#../...../..#../..#../.#...");
  def("-", "...../...../...../.###./...../...../.....");
  def("+", "...../..#../..#../#####/..#../..#../.....");
  def("=", "...../...../#####/...../#####/...../.....");
  def("/", "....#/....#/...#./..#../.#.../#..../#....");
  def("\\", "#..../#..../.#.../..#../...#./....#/....#");
  def("(", "...#./..#../.#.../.#.../.#.../..#../...#.");
  def(")", ".#.../..#../...#./...#./...#./..#../.#...");
  def("<", "...#./..#../.#.../#..../.#.../..#../...#.");
  def(">", ".#.../..#../...#./....#/...#./..#../.#...");
  def("%", "##..#/##..#/...#./..#../.#.../#..##/#..##");
  def("$", "..#../.####/#.#../.###./..#.#/####./..#..");
  def("&", ".##../#..#./#..#./.##../#.#.#/#..#./.##.#");
  def("*", "...../#.#.#/.###./#####/.###./#.#.#/.....");
  def("#", ".#.#./#####/.#.#./.#.#./#####/.#.#./.....");
  def("_", "...../...../...../...../...../...../#####");
  def("|", "..#../..#../..#../..#../..#../..#../..#..");

  // Arcade furniture: middot, arrows, a cursor block, a heart, a coin.
  def("·", "...../...../...../..#../...../...../.....");   // ·
  def("←", "...../..#../.#.../#####/.#.../..#../.....");   // ←
  def("→", "...../..#../...#./#####/...#./..#../.....");   // →
  def("↑", "..#../.###./#.#.#/..#../..#../..#../.....");   // ↑
  def("↓", "..#../..#../..#../#.#.#/.###./..#../.....");   // ↓
  def("▮", "#####/#####/#####/#####/#####/#####/#####");   // ▮
  def("▲", "..#../..#../.###./.###./#####/#####/.....");   // ▲
  def("▼", "...../#####/#####/.###./.###./..#../.....");   // ▼
  def("◀", "...#./..##./.###./####./.###./..##./...#.");   // ◀
  def("▶", ".#.../.##../.###./.####/.###./.##../.#...");   // ▶

  var UNKNOWN = ".###./#...#/#.#.#/#..##/#.#.#/#...#/.###.".split("/");

  var CW = 5, CH = 7, GAP = 1;

  // Typographic characters that will inevitably appear in prose get folded
  // onto glyphs we actually have, rather than rendering as a box. Accented
  // letters lose their marks, which is the right trade in a 5x7 cell.
  var FOLD = {
    "\u2014": "-", "\u2013": "-", "\u2212": "-",       // em/en dash, minus
    "\u2018": "'", "\u2019": "'", "\u02BC": "'",       // curly single quotes
    "\u201C": '"', "\u201D": '"',                       // curly double quotes
    "\u00D7": "*", "\u2022": "\u00B7", "\u00A0": " ",
    "\u00E9": "E", "\u00E8": "E", "\u00EA": "E",
    "\u00E1": "A", "\u00E0": "A", "\u00E2": "A",
    "\u00ED": "I", "\u00F3": "O", "\u00FA": "U",
    "\u00F1": "N", "\u00E7": "C", "\u00FC": "U", "\u00F6": "O", "\u00E4": "A"
  };

  // "..." is three cells wide, so an ellipsis expands rather than folds.
  function normalise(str) {
    str = String(str).replace(/\u2026/g, "...");
    var out = "", i, ch;
    for (i = 0; i < str.length; i++) {
      ch = str.charAt(i);
      out += (FOLD[ch] !== undefined) ? FOLD[ch] : ch;
    }
    return out;
  }

  function glyph(ch) {
    return G[ch] || G[ch.toUpperCase()] || UNKNOWN;
  }

  function measure(str, scale) {
    str = normalise(str);
    if (!str.length) return 0;
    return (str.length * (CW + GAP) - GAP) * scale;
  }

  // Draws `str` with its top-left at (x, y). Integer scale only.
  function draw(ctx, str, x, y, scale, color) {
    str = normalise(str);
    scale = Math.max(1, Math.round(scale || 1));
    ctx.fillStyle = color;
    var px = Math.round(x), py = Math.round(y);
    for (var i = 0; i < str.length; i++) {
      var ch = str.charAt(i);
      if (ch !== " ") {
        var rows = glyph(ch);
        for (var r = 0; r < CH; r++) {
          var row = rows[r], run = 0;
          // Emit horizontal runs as single rects: fewer draw calls, same pixels.
          for (var c = 0; c <= CW; c++) {
            if (c < CW && row.charAt(c) === "#") { run++; continue; }
            if (run) {
              ctx.fillRect(px + (c - run) * scale, py + r * scale, run * scale, scale);
              run = 0;
            }
          }
        }
      }
      px += (CW + GAP) * scale;
    }
  }

  global.PixelFont = {
    CW: CW, CH: CH, GAP: GAP,
    advance: function (scale) { return (CW + GAP) * scale; },
    lineHeight: function (scale) { return (CH + 2) * scale; },
    measure: measure,
    draw: draw,
    normalise: normalise,
    has: function (ch) {
      ch = normalise(ch).charAt(0);
      return !!(G[ch] || G[ch.toUpperCase()]);
    }
  };
})(window);
